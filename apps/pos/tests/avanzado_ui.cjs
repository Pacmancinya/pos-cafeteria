const assert = require('node:assert/strict');
const L = require('../static/inventario-logica.js');
assert.equal(L.venta(1200,50),1800); assert.equal(L.costo(1800,50),1200);
assert.equal(L.ganancia(1200,1800),50); assert.equal(L.ganancia(0,1800),null);
assert.equal(L.venta(0,50),0);
assert.equal(L.redondear(2401,10),2410); assert.equal(L.redondear(2401,50),2450);
assert.equal(L.redondear(2400,50),2400);
assert.equal(L.sugerido(1200,50,50),2400); assert.equal(L.sugerido(1201,50,50),2450);
assert.equal(L.sugerido(0,50,50),0); assert.equal(L.sugerido(1200,100,50),0);
assert.equal(L.normalizar('  TÉ frío ÁRBOL Ñ  '),'te frio arbol n');
const p = {nombre:'Café frío',plu:'0007',codigos:[{codigo:'0036000291452'}]};
for(const q of ['CAFE','frío','FRIO','0007','7','0036000291452']) assert(L.coincide(p,q),q);
assert(L.exacto(p,'036000291452')); assert(!L.exacto(p,'3600029145'));
assert(!L.coincide(p,'torta'));
assert(L.porComprar({cuenta:true,minimo:3,stock:2}));
assert(!L.porComprar({cuenta:false,minimo:3,stock:2}));
console.log('Precios, redondeo, sugerido, tildes, PLU y códigos: OK');
